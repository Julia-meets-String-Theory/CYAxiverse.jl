"""
    CYAxiverse
A Julia package for computing axion/ALP spectra and statistics using geometric data generated by [CYTools](https://cytools.liammcallistergroup.com/).

Load the optional CYTools integration after `using CYAxiverse`:
```julia
using PyCall
const CYTools = Base.get_extension(CYAxiverse, :CYAxiversePyCallExt)
CYTools.enable_cytools!()
```

When `CYAXIVERSE_PYTHON` is set, `enable_cytools!()` verifies that PyCall was
built for that interpreter. It never rebuilds PyCall automatically.
"""
module CYAxiverse

"""
    KINETIC_NORMALIZATION

The axion kinetic normalization of every physical result CYAxiverse computes
from the stored inverse Kähler metric `Kinv`: `:sugra_c1`, the literal
𝒩 = 1 supergravity normalization (CYAX-0232). The kinetic term is
`-(1/2) M_pl² K ∂ϑ ∂ϑ` with `K = 2 Kinv⁻¹` and period-one ϑ; see
`read.kinetic_factor` and `read.kinetic_matrix`.
"""
const KINETIC_NORMALIZATION = :sugra_c1

include("structs.jl")
include("python_interpreter.jl")
include("filestructure.jl")
include("read.jl")
include("minimizer.jl")
include("generate.jl")
include("jlm_reduced.jl")
include("paper_benchmarks.jl")
include("inflation_points.jl")
include("axion_photon.jl")
include("scientific_certification.jl")

# Keep the historical module binding as a narrow compatibility alias. New
# code should use `CYAxiverse.axion_photon`, whose name describes the physics.
const glimmers = axion_photon

"""Scientific namespace for the deterministic axion benchmark models."""
const axion_benchmarks = paper_benchmarks

include("../add_functions/profiling.jl")
include("plotting.jl")

if haskey(ENV, "SLURM_JOB_ID")
    include("slurm.jl")
end

using .read: kinetic_factor, kinetic_matrix

export greet_CYAxiverse, KINETIC_NORMALIZATION, kinetic_factor, kinetic_matrix

"""
    greet_CYAxiverse()

Return the package's standard greeting.
"""
greet_CYAxiverse() = "Hello CYAxiverse!"

end
